  const Progress = {
    key(email) { return 'manara_progress_' + email; },

    all() {
      const u = Auth.current();
      if (!u) return {};
      return store.get(this.key(u.email), {});
    },

    save(data) {
      const u = Auth.current();
      if (!u) return;
      store.set(this.key(u.email), data);
    },

    toggleTask(programId, taskId, done) {
      const data = this.all();
      data[programId] = data[programId] || { tasks: {}, log: [] };
      data[programId].tasks[taskId] = !!done;
      const today = new Date().toISOString().slice(0, 10);
      if (done && !data[programId].log.includes(today)) data[programId].log.push(today);
      this.save(data);
    },

    programStats(programId) {
      const prog = PROGRAMS[programId];
      if (!prog) return { total: 0, done: 0, pct: 0, daysDone: 0, daysTotal: 0 };
      const saved = (this.all()[programId] || { tasks: {} }).tasks;
      let total = 0, done = 0, daysDone = 0, daysTotal = 0;
      prog.phases.forEach((ph, pi) => {
        ph.days.forEach((d, di) => {
          daysTotal++;
          let dayAll = true;
          d.tasks.forEach((t, ti) => {
            total++;
            const id = `p${pi}d${di}t${ti}`;
            if (saved[id]) done++; else dayAll = false;
          });
          if (dayAll && d.tasks.length) daysDone++;
        });
      });
      return { total, done, pct: total ? Math.round(done / total * 100) : 0, daysDone, daysTotal };
    },

    activeDays() {
      const data = this.all();
      const set = new Set();
      Object.values(data).forEach(p => (p.log || []).forEach(d => set.add(d)));
      return set;
    },

    streak() {
      const days = this.activeDays();
      let streak = 0;
      const d = new Date();
      // اليوم الحالي يُحسب إن كان نشطاً، وإلا نبدأ من الأمس
      if (!days.has(d.toISOString().slice(0, 10))) d.setDate(d.getDate() - 1);
      while (days.has(d.toISOString().slice(0, 10))) {
        streak++;
        d.setDate(d.getDate() - 1);
      }
      return streak;
    }
  };

