  const $ = (s, c) => (c || document).querySelector(s);
  const $$ = (s, c) => Array.from((c || document).querySelectorAll(s));
  const store = {
    get(k, d) { try { return JSON.parse(localStorage.getItem(k)) ?? d; } catch { return d; } },
    set(k, v) { localStorage.setItem(k, JSON.stringify(v)); }
  };

  /* ============================================================
     1) المصادقة (تسجيل / دخول / خروج)
     ============================================================ */
  const Auth = {
    usersKey: 'manara_users',
    sessionKey: 'manara_session',

    users() { return store.get(this.usersKey, []); },

    current() {
      const email = store.get(this.sessionKey, null);
      if (!email) return null;
      return this.users().find(u => u.email === email) || null;
    },

    register(name, email, pass, goal) {
      email = email.trim().toLowerCase();
      if (!name.trim() || name.trim().length < 2) throw new Error('يرجى إدخال اسمك الكامل.');
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw new Error('البريد الإلكتروني غير صالح.');
      if (pass.length < 6) throw new Error('كلمة المرور يجب أن تكون 6 أحرف على الأقل.');
      const users = this.users();
      if (users.some(u => u.email === email)) throw new Error('هذا البريد مسجَّل مسبقاً — يمكنك تسجيل الدخول مباشرة.');
      users.push({
        name: name.trim(), email,
        pass: btoa(unescape(encodeURIComponent(pass))),
        goal: goal || 'confidence',
        joined: new Date().toISOString()
      });
      store.set(this.usersKey, users);
      store.set(this.sessionKey, email);
      return true;
    },

    login(email, pass) {
      email = email.trim().toLowerCase();
      const u = this.users().find(x => x.email === email);
      if (!u || u.pass !== btoa(unescape(encodeURIComponent(pass)))) {
        throw new Error('البريد الإلكتروني أو كلمة المرور غير صحيحة.');
      }
      store.set(this.sessionKey, email);
      return true;
    },

    logout() {
      localStorage.removeItem(this.sessionKey);
      location.href = relPath() + 'index.html';
    }
  };

