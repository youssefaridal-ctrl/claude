import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

async function main() {
  const result = await build({
    entryPoints: [path.join(root, 'assets/web/kitchen3d/src/scene.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'KitchenScene',
    target: 'es2018',
    minify: true,
    write: false,
    logLevel: 'info',
  });

  const bundleJs = result.outputFiles[0].text;

  const template = readFileSync(path.join(root, 'assets/web/kitchen3d/template.html'), 'utf8');
  const finalHtml = template.replace('__SCENE_BUNDLE__', () => bundleJs);

  const outDir = path.join(root, 'src/generated');
  mkdirSync(outDir, { recursive: true });

  const tsContent = `// AUTO-GENERATED by scripts/build-kitchen3d.mjs — do not edit by hand.\nexport const KITCHEN3D_HTML = ${JSON.stringify(finalHtml)};\n`;
  writeFileSync(path.join(outDir, 'kitchen3dHtml.ts'), tsContent, 'utf8');

  console.log(`kitchen3dHtml.ts written (${(tsContent.length / 1024).toFixed(1)} KB)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
